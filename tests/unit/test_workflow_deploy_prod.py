def test_metadata_tags_preserve_semver_and_ref_conventions() -> None:
    for step in _metadata_steps():
        tags = step["with"]["tags"]
        assert "type=ref,event=tag,suffix={{sha}}" in tags
        assert "type=semver,pattern={{version}}" in tags
        assert "type=semver,pattern={{major}}.{{minor}}" in tags
        assert "type=semver,pattern={{major}}" in tags


