# ---------------------------------------------------------------------------
# Production image-selection regression tests
#
# Before the fix, the production deploy job set only IMAGE_TAG (from
# github.ref_name) and exported it for Compose. Since docker-compose.prod.yml
# reads DOCKER_IMAGE and FRONTEND_IMAGE (not IMAGE_TAG), both services
# silently fell back to the 'latest' tag.
#
# The fix sets DOCKER_IMAGE and FRONTEND_IMAGE from the immutable digests
# produced by the build job, validates them, and explicitly pulls before
# recreating services.
# ---------------------------------------------------------------------------


def _deploy_step() -> dict:
    """Return the 'Deploy to production host' step from the deploy job."""
    wf = _load_workflow()
    return next(
        s for s in wf["jobs"]["deploy"]["steps"] if s.get("name") == "Deploy to production host"
    )


def _rollback_step() -> dict:
    """Return the 'Rollback on failure' step from the deploy job."""
    wf = _load_workflow()
    return next(s for s in wf["jobs"]["deploy"]["steps"] if s.get("name") == "Rollback on failure")


def _deploy_script() -> str:
    return _deploy_step()["with"]["script"]


def _rollback_script() -> str:
    return _rollback_step()["with"]["script"]


