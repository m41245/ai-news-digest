def test_deploy_step_validates_digests_before_recreate() -> None:
    """The deploy step must validate image digests are non-empty before compose up."""
    script = _deploy_script()
    assert "needs.build-and-push.outputs.backend-digest" in script
    assert "needs.build-and-push.outputs.frontend-digest" in script
    assert "[ -z" in script, "Deploy script must include a non-empty check for digests"
    assert "exit 1" in script, "Deploy script must fail when digests are missing"


def test_deploy_step_validation_occurs_before_pull() -> None:
    """Validation must occur before GHCR login and image pull."""
    script = _deploy_script()
    validation_pos = script.index("[ -z")
    login_pos = script.index("docker login ghcr.io")
    pull_pos = script.index('docker pull "$DOCKER_IMAGE"')
    assert validation_pos < login_pos, "Validation must occur before GHCR login"
    assert login_pos < pull_pos, "GHCR login must occur before image pull"


def test_deploy_step_pull_occurs_before_compose_up() -> None:
    """Image pull must occur before docker compose up."""
    script = _deploy_script()
    pull_pos = script.index('docker pull "$DOCKER_IMAGE"')
    up_pos = script.index(
        "docker compose -f docker-compose.prod.yml --env-file .env.prod.local up -d --force-recreate"
    )
    assert pull_pos < up_pos, "Image pull must occur before service recreation"


