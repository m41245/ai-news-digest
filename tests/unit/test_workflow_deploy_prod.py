def test_production_triggers_remain_intact() -> None:
    """Production workflow must preserve release, tag, and workflow_dispatch triggers."""
    wf = _load_workflow()
    # YAML 1.1 interprets bare 'on' as boolean True
    triggers = wf.get(True) or wf.get("on")
