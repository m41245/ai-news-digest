"""
Tests for the staging deployment workflow (deploy-staging.yml).

Validates:
- Workflow structure and job dependencies.
- Frontend image reference is passed through to the remote deployment.
- Rollback function explicitly pulls the previous backend image.
- Rollback also captures and pulls the previous frontend image.
- Deployment-status step correctly distinguishes skipped vs successful deployment.
- Migration integrity gate uses the exact backend image from the current workflow run.
- Rollback preserves the deployment failure (exit nonzero).
- Migration warning is present in rollback.
- Backend and frontend metadata are generated by SEPARATE metadata-action steps
  (no shared tag output that could cause one image to overwrite the other).
- Each build-and-push step consumes only its own image-specific metadata output.
- The immutable SHA-based staging tag and the staging-latest convenience tag
  are preserved and match the deployment references.
"""

from __future__ import annotations

import pathlib

import yaml

_WORKFLOW_PATH = (
    pathlib.Path(__file__).resolve().parents[2] / ".github" / "workflows" / "deploy-staging.yml"
)


def _load_workflow() -> dict:
    assert _WORKFLOW_PATH.exists(), f"Workflow not found at {_WORKFLOW_PATH}"
    return yaml.safe_load(_WORKFLOW_PATH.read_text(encoding="utf-8"))


def _bp_steps() -> list[dict]:
    """Return the build-and-push job's steps."""
    wf = _load_workflow()
    return wf["jobs"]["build-and-push"]["steps"]


def _metadata_steps() -> list[dict]:
    """Return all docker/metadata-action steps in the build-and-push job."""
    return [s for s in _bp_steps() if s.get("uses") == "docker/metadata-action@v5"]


def _build_push_steps() -> list[dict]:
    """Return all docker/build-push-action steps in the build-and-push job."""
    return [s for s in _bp_steps() if s.get("uses") == "docker/build-push-action@v6"]


def _step_by_id(steps: list[dict], step_id: str) -> dict:
    return next(s for s in steps if s.get("id") == step_id)


def _deploy_script() -> str:
    wf = _load_workflow()
    deploy_job = wf["jobs"]["deploy"]
    deploy_step = next(s for s in deploy_job["steps"] if s.get("name") == "Deploy to staging host")
    return deploy_step["with"]["script"]


def _status_script() -> str:
    wf = _load_workflow()
    status_step = next(
        s
        for s in wf["jobs"]["deployment-status"]["steps"]
        if s.get("name") == "Check deployment result"
    )
    return status_step["run"]


def _migrate_script() -> str:
    wf = _load_workflow()
    migrate_step = next(
        s
        for s in wf["jobs"]["build-and-push"]["steps"]
        if s.get("name") == "Verify migration integrity of backend image"
    )
    return migrate_step["run"]


