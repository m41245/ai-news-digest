# ---------------------------------------------------------------------------
# Tag collision / metadata separation tests
#
# A single docker/metadata-action step that declares both the backend and
# frontend images produces a combined ``tags`` output. Both build-and-push
# steps would then consume the same combined output, causing each build to
# push tags to *both* image repositories — a tag collision where one image
# can overwrite the other.
#
# These tests enforce that each image has its own isolated metadata step and
# that each build-and-push step consumes only its own metadata output.
# ---------------------------------------------------------------------------


def test_there_is_no_shared_metadata_step() -> None:
    """No metadata-action step should declare both backend and frontend images."""
    for step in _metadata_steps():
        images = step["with"]["images"]
        assert "\n" not in images.strip(), (
            f"Metadata step '{step.get('id')}' declares multiple images on "
            f"separate lines — this creates a shared tag output that can cause "
            "one image to overwrite the other. Split into per-image metadata steps."
        )


def test_backend_metadata_step_exists() -> None:
    steps = _metadata_steps()
    assert any(
        s.get("id") == "meta-backend" for s in steps
    ), "A metadata-action step with id 'meta-backend' must exist"


def test_frontend_metadata_step_exists() -> None:
    steps = _metadata_steps()
    assert any(
        s.get("id") == "meta-frontend" for s in steps
    ), "A metadata-action step with id 'meta-frontend' must exist"


def test_metadata_steps_are_distinct() -> None:
    steps = _metadata_steps()
    assert (
        len(steps) == 2
    ), f"Expected exactly two metadata-action steps (backend and frontend), found {len(steps)}"
    ids = {s.get("id") for s in steps}
    assert ids == {"meta-backend", "meta-frontend"}


def test_backend_metadata_contains_only_backend_image() -> None:
    meta = _step_by_id(_metadata_steps(), "meta-backend")
    images = meta["with"]["images"]
